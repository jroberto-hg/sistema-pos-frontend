import express from 'express';
import Database from 'better-sqlite3';

import { ProcessFileChange } from './application/use-cases/ProcessFileChange';
import { DbInitializer } from './infrastructure/database/DbInitializer';
import { NodeCryptoHash } from './infrastructure/security/NodeCryptoHash';
import { SqliteDocumentGateway } from './infrastructure/database/SqliteDocumentGateway';
import { ChokidarVaultWatcher } from './infrastructure/watcher/ChokidarVaultWatcher';
import { NodeIdentity } from './infrastructure/identity/NodeIdentity';
import { WikiIdentity } from './infrastructure/identity/WikiIdentity';

const app = express();
app.use(express.json());

const VAULT_DIR = './src/vault';

// 1. Identidad Local del Nodo y Wiki
const NODE_ID = NodeIdentity.getOrCreateNodeId();
const WIKI_ID = WikiIdentity.getOrCreateWikiId(VAULT_DIR);


//Inicializar Base de Datos
const db = new Database('./ciudadan.db');
DbInitializer.initialize(db);

db.exec(`
    INSERT OR IGNORE INTO nodes (node_id, name, public_key) 
    VALUES ('${NODE_ID}', 'Nodo Local AutoGenerated', 'pub_key_placeholder');
    
    INSERT OR IGNORE INTO wikis (wiki_id, node_id, name, slug, visibility) 
    VALUES ('${WIKI_ID}', '${NODE_ID}', 'Wiki Vault Local', 'local', 'public');
`);

//Gateways (Infraestructura)
const documentGateway = new SqliteDocumentGateway(db);
const hashGateway = new NodeCryptoHash();
const vaultWatcher = new ChokidarVaultWatcher();

//Caso de Uso
const processFileChange = new ProcessFileChange(documentGateway, hashGateway);

//Conectar evententos de infraestructura a Caso de Uso
vaultWatcher.onFileChanged(async (filePath, content) => {
    console.log(`\n⚡ [Watcher Evento] Archivo detectado: ${filePath}`);
    try {
        await processFileChange.execute(WIKI_ID, filePath, content, NODE_ID);
    } catch (error) {
        console.error(`[Error] Fallo al procesar ${filePath}:`, error);
    }
});

//Iniciar Monitoreo del Vault
vaultWatcher.startWatching(VAULT_DIR);

//Levantar Servidor
const PORT = process.env.PORT || 3000;
app.listen(PORT, () => {
    console.log(`\n🚀 Servidor escuchando en http://localhost:${PORT}`);
    console.log(`👀 Listo para detectar cambios en: ${VAULT_DIR}\n`);
});